# Copy Method.

dict_a = {
    
    "name": "Abhinav",
    "age": 26,
    "City": "Delhi"
    
}

dict_a_copy = dict_a.copy()

print(dict_a_copy)

# Length Method.

dict_a = {
    
    "name": "Abhinav",
    "age": 26,
    "City": "Delhi"
    
}

print(len(dict_a))

# Clear Method.

dict_a = {
    
    "name": "Abhinav",
    "age": 26,
    "City": "Delhi"
    
}

dict_a.clear()

print(dict_a)

